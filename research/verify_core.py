seen=set()
for h in range(64):
    if h not in seen:
        o={h, rev(h)}
        zong_orbits.append(o); seen|=o
# orbits under group generated by flip and rev
seen=set(); G=[]
for h in range(64):
    if h in seen: continue
    o={h}
