# ---------- 1. Dayan divination: 49 rods, 3 changes, one line ----------
# Uniform split over valid L (right pile needs >= 2 so hang-one works).
# Use DP over the remaining count; counting paths overweights narrow branches.
def stage(n):
    d = {}
    for L in range(1, n - 1):
        R = n - L
        rl = L % 4 or 4
        rr = (R - 1) % 4 or 4
        take = rl + rr + 1
        d[n - take] = d.get(n - take, 0.0) + 1.0 / (n - 2)
    return d

dist = {49: 1.0}
for _ in range(3):
    nxt = {}
    for n, p in dist.items():
        for r, q in stage(n).items():
            nxt[r] = nxt.get(r, 0.0) + p * q
    dist = nxt

print("== 1. Dayan (49 rods, 3 changes, strict uniform split) ==")
for n in sorted(dist, reverse=True):
    v = n // 4
